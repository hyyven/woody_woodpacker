#include "../../includes/woody.h"

int	is_file(char *f_path)
{
	int	fd;
	
	fd = open(f_path, O_RDONLY);
	if (fd < 0)
	{
		perror("[ERROR] open");
		exit(1);
	}
	return (fd);
}